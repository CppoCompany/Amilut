-- =============================================================================
-- 014_create_countries
-- Creates the `countries` lookup table inside the `Amilut` database and seeds
-- it with the ISO 3166-1 alpha-2 country list (Hebrew display name + code).
-- The `key` is the two-letter ISO code used for CSR / customs declarations.
--
-- Run this file against the `Amilut` database. The runner issues
-- `SET ROLE "Admin"` first, so every object created here is owned by `Admin`.
--
-- Idempotent: CREATE TABLE IF NOT EXISTS, and the seed uses
-- ON CONFLICT (key) DO NOTHING, so re-running never duplicates rows and never
-- overwrites a name that was edited later.
-- =============================================================================

-- ---- countries ----------------------------------------------------------------
CREATE TABLE IF NOT EXISTS countries (
    id    SERIAL      PRIMARY KEY,
    name  TEXT        NOT NULL,               -- Hebrew display name
    key   CHAR(2)     NOT NULL UNIQUE          -- ISO 3166-1 alpha-2 code (for CSR)
        CHECK (key ~ '^[A-Z]{2}$')
);

